<?php

namespace App\Support;

use App\Models\EmployeeDocument;
use App\Models\EmployeeDocumentFile;
use Carbon\Carbon;

class GeneratedDocumentExpiry
{
    private const GENERATED_FILE_CHANGE_NOTES = 'Generated by HR upon approval';

    public static function isLetterRequest(EmployeeDocument $document): bool
    {
        return $document->documentType?->category?->short_code === 'letter_requests';
    }

    public static function isExpired(EmployeeDocument $document): bool
    {
        if (! self::isLetterRequest($document)) {
            return false;
        }

        $generatedFile = self::generatedFile($document);
        if (! $generatedFile) {
            return false;
        }

        if ($document->expiry_date) {
            return $document->expiry_date->lt(Carbon::today());
        }

        $generatedAt = $generatedFile->uploaded_date ?? $document->created_at;

        return $generatedAt?->copy()->addMonths(3)->startOfDay()->lt(Carbon::today()) ?? false;
    }

    private static function generatedFile(EmployeeDocument $document): ?EmployeeDocumentFile
    {
        if ($document->relationLoaded('files')) {
            return $document->files
                ->where('change_notes', self::GENERATED_FILE_CHANGE_NOTES)
                ->sortByDesc('id')
                ->first();
        }

        return $document->files()
            ->where('change_notes', self::GENERATED_FILE_CHANGE_NOTES)
            ->latest('id')
            ->first();
    }
}
