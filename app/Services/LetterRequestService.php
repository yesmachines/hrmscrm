<?php

namespace App\Services;

use App\Models\EmployeeDocument;
use App\Models\EmployeeDocumentFile;
use App\Models\EmployeeDocumentHistory;
use App\Models\SalesCrm\Employee;
use Barryvdh\DomPDF\Facade\Pdf;
use Carbon\Carbon;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Http\Request;
use Illuminate\Pagination\LengthAwarePaginator;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

class LetterRequestService
{
    public function listForHr(Request $request): LengthAwarePaginator
    {
        $query = EmployeeDocument::query()
            ->with([
                'employee.user:id,name,email',
                'employee.department:id,name',
                'employee.organisation:id,org_name',
                'documentType',
                'documentTemplate',
                'requestDetails',
                'histories' => fn ($builder) => $builder->orderByDesc('id'),
                'files' => fn ($builder) => $builder->orderByDesc('id'),
            ])
            ->whereHas('documentType.category', function (Builder $builder): void {
                $builder->where('short_code', 'letter_requests');
            });

        if ($request->filled('status')) {
            $query->where('status', $request->input('status'));
        }

        if ($request->filled('search')) {
            $search = $request->input('search');
            $query->where(function (Builder $builder) use ($search): void {
                $builder->where('document_title', 'like', "%{$search}%")
                    ->orWhereHas('documentType', function (Builder $typeQuery) use ($search): void {
                        $typeQuery->where('document_name', 'like', "%{$search}%");
                    });
            });
        }

        $perPage = max(1, min(100, (int) $request->input('per_page', 15)));

        return $query->orderByDesc('id')->paginate($perPage)->withQueryString();
    }

    public function findForHr(int $id): EmployeeDocument
    {
        return EmployeeDocument::query()
            ->with([
                'employee.user:id,name,email',
                'employee.department:id,name',
                'employee.organisation:id,org_name',
                'documentType',
                'documentTemplate',
                'requestDetails',
                'histories' => fn ($builder) => $builder->orderByDesc('id'),
                'files' => fn ($builder) => $builder->orderByDesc('id'),
            ])
            ->whereHas('documentType.category', function (Builder $builder): void {
                $builder->where('short_code', 'letter_requests');
            })
            ->findOrFail($id);
    }

    /**
     * @param  array<string, mixed>  $approvedDetails
     */
    public function approve(EmployeeDocument $letterRequest, array $approvedDetails, int $actorId): void
    {
        DB::transaction(function () use ($letterRequest, $approvedDetails, $actorId): void {
            $letterRequest = EmployeeDocument::query()
                ->lockForUpdate()
                ->findOrFail($letterRequest->id);
            $this->ensureLetterRequest($letterRequest);
            $this->ensurePending($letterRequest);

            $letterRequest->update([
                'status' => 'approved',
                'remarks' => $approvedDetails['remarks'] ?? null,
            ]);

            $temporaryDetails = array_intersect_key(
                $approvedDetails,
                array_flip(['salary_amount', 'bank_iban', 'to_address', 'destination_country', 'purpose']),
            );
            $html = $this->renderDocumentHtml($letterRequest, null, $temporaryDetails);

            if ($html !== null) {
                $pdfHtml = '<!DOCTYPE html>
<html>
<head>
    <meta http-equiv="Content-Type" content="text/html; charset=utf-8"/>
    <style>
        body { font-family: "DejaVu Sans", sans-serif; }
        p, div, span, table { max-width: 100% !important; }
        p { margin-right: 0 !important; padding-right: 0 !important; width: auto !important; }
    </style>
</head>
<body>'.$html.'</body>
</html>';
                $pdf = Pdf::loadHTML($pdfHtml)->setPaper('a4', 'portrait');
                $filename = 'letters/'.Str::slug($letterRequest->document_number ?: 'doc-'.$letterRequest->id).'-'.time().'.pdf';

                Storage::disk('public')->put($filename, $pdf->output());

                EmployeeDocumentFile::query()->create([
                    'employee_document_id' => $letterRequest->id,
                    'version_no' => '1.0',
                    'file_path' => $filename,
                    'uploaded_by' => $actorId,
                    'uploaded_date' => Carbon::now(),
                    'change_notes' => 'Generated by HR upon approval',
                ]);
            }

            EmployeeDocumentHistory::query()->create([
                'employee_document_id' => $letterRequest->id,
                'action_type' => 'approved',
                'remarks' => array_key_exists('remarks', $approvedDetails)
                    ? $approvedDetails['remarks']
                    : 'Letter approved and generated by HR',
                'done_by' => $actorId,
                'action_on' => Carbon::now(),
            ]);
        });
    }

    public function reject(EmployeeDocument $letterRequest, string $remarks, int $actorId): void
    {
        DB::transaction(function () use ($letterRequest, $remarks, $actorId): void {
            $letterRequest = EmployeeDocument::query()
                ->lockForUpdate()
                ->findOrFail($letterRequest->id);
            $this->ensureLetterRequest($letterRequest);
            $this->ensurePending($letterRequest);

            $letterRequest->update([
                'status' => 'rejected',
                'remarks' => $remarks,
            ]);

            EmployeeDocumentHistory::query()->create([
                'employee_document_id' => $letterRequest->id,
                'action_type' => 'rejected',
                'remarks' => $remarks,
                'done_by' => $actorId,
                'action_on' => Carbon::now(),
            ]);
        });
    }

    public function renderDocumentHtml(
        EmployeeDocument $document,
        ?Employee $employee = null,
        array $temporaryDetails = [],
    ): ?string {
        $document->loadMissing(['documentType', 'documentTemplate', 'requestDetails']);
        $employee ??= Employee::query()
            ->with(['user', 'department', 'organisation'])
            ->find($document->employee_id);

        $template = $document->documentTemplate
            ?? $document->documentType?->resolveTemplate($employee?->organisation_id);

        if (! $template || empty($template->template_code)) {
            return null;
        }

        $details = $document->requestDetails->pluck('field_value', 'field_key')->all();
        $details = array_merge($details, array_filter($temporaryDetails));
        $employee?->loadMissing(['user', 'department', 'organisation']);

        $grossSalary = (float) ($employee?->gross_salary ?? 0);
        $formatter = new \NumberFormatter('en', \NumberFormatter::SPELLOUT);
        $salaryInWords = ucwords($formatter->format($grossSalary));

        $replacements = [
            '{{company_name}}' => $employee?->organisation?->org_name ?? config('app.name', 'HRMS'),
            '{{company_address}}' => 'Dubai, United Arab Emirates',
            '{{company_phone}}' => '+971 4 000 0000',
            '{{company_email}}' => 'hr@company.com',
            '{{employee_name}}' => $employee?->user?->name ?? "Employee #{$document->employee_id}",
            '{{employee_code}}' => $employee?->emp_num ?? "EMP-{$document->employee_id}",
            '{{passport_number}}' => '—',
            '{{emirates_id}}' => '—',
            '{{designation}}' => $details['visa_designation'] ?? ($employee?->designation ?? 'Employee'),
            '{{department}}' => $employee?->department?->name ?? 'General',
            '{{joining_date}}' => $employee?->joining_date
                ? Carbon::parse($employee->joining_date)->format('d M Y')
                : '—',
            '{{basic_salary}}' => $employee?->basic_salary
                ? number_format((float) $employee->basic_salary, 2)
                : '0.00',
            '{{housing_allowance}}' => $employee?->housing_allowance
                ? number_format((float) $employee->housing_allowance, 2)
                : '0.00',
            '{{other_allowance}}' => '0.00',
            '{{gross_salary}}' => $employee?->gross_salary ? number_format($grossSalary, 2) : '0.00',
            '{{gross_salary_in_words}}' => 'Dirhams '.$salaryInWords.' only',
            '{{document_number}}' => $document->document_number
                ?: ('DOC-'.str_pad((string) $document->id, 5, '0', STR_PAD_LEFT)),
            '{{issue_date}}' => $document->issue_date
                ? $document->issue_date->format('d M Y')
                : Carbon::now()->format('d M Y'),
            '{{purpose}}' => $details['purpose'] ?? 'Official Purpose',
            '{{to_address}}' => $details['to_address'] ?? 'To Whom It May Concern',
            '{{visa_designation}}' => $details['visa_designation'] ?? ($employee?->designation ?? 'Employee'),
            '{{payroll_month}}' => Carbon::now()->format('F Y'),
            '{{net_salary}}' => $employee?->gross_salary
                ? number_format((float) $employee->gross_salary, 2)
                : '0.00',
            '{{gross_earnings}}' => $employee?->gross_salary
                ? number_format((float) $employee->gross_salary, 2)
                : '0.00',
            '{{deductions_unpaid}}' => '0.00',
            '{{deductions_other}}' => '0.00',
            '{{total_deductions}}' => '0.00',
            '{{transport_allowance}}' => '0.00',
            '{{bank_account_masked}}' => '•••• •••• •••• 1234',
            '{{bank_name}}' => 'Emirates NBD',
            '{{account_number}}' => '1234567890',
            '{{iban_number}}' => 'AE000000000000000000000',
            '{{company_stamp_url}}' => file_exists(public_path('images/sample-stamp.jpg'))
                ? 'data:image/jpeg;base64,'.base64_encode(file_get_contents(public_path('images/sample-stamp.jpg')))
                : '',
            '{{company_signature_url}}' => file_exists(public_path('images/sample-signature.png'))
                ? 'data:image/png;base64,'.base64_encode(file_get_contents(public_path('images/sample-signature.png')))
                : '',
        ];

        foreach ($details as $key => $value) {
            $replacements['{{'.$key.'}}'] = (string) $value;
        }

        return str_replace(array_keys($replacements), array_values($replacements), $template->template_code);
    }

    private function ensureLetterRequest(EmployeeDocument $letterRequest): void
    {
        $letterRequest->loadMissing('documentType.category');

        abort_unless($letterRequest->documentType?->category?->short_code === 'letter_requests', 404);
    }

    private function ensurePending(EmployeeDocument $letterRequest): void
    {
        abort_unless(
            in_array($letterRequest->status, ['submitted', 'under_review'], true),
            409,
            'Only pending letter requests can be processed.',
        );
    }
}
